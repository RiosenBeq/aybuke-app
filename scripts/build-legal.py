#!/usr/bin/env python3
"""Render the legal documents from legal/{en,tr}/*.md and legal/config.json.

    python3 scripts/build-legal.py           # write the outputs
    python3 scripts/build-legal.py --check   # fail if any output is stale (CI)

Outputs (generated, do not edit by hand):
  ios/App/Resources/Legal/<lang>/<name>.md  bundled in the app; links between
                                            documents use glowlit-legal://<id>
  docs/legal/<lang>/<name>.md               public copies on GitHub, with
                                            relative links between documents
  web/legal/<lang>/<name>.html              pages for the website (web/)
"""

from __future__ import annotations

import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "legal"
APP_OUT = ROOT / "ios" / "App" / "Resources" / "Legal"
DOCS_OUT = ROOT / "docs" / "legal"
WEB_OUT = ROOT / "web" / "legal"

# Document id (as used by LegalDocument in the app) → file name per language.
DOCUMENTS = {
    "terms": {"en": "terms-of-use", "tr": "kullanim-kosullari"},
    "privacy": {"en": "privacy-policy", "tr": "gizlilik-politikasi"},
    "acceptableUse": {"en": "acceptable-use-policy", "tr": "kabul-edilebilir-kullanim-politikasi"},
    "kvkk": {"tr": "kvkk-aydinlatma-metni"},
}
LINK_TOKENS = {"LINK_TERMS": "terms", "LINK_PRIVACY": "privacy", "LINK_AUP": "acceptableUse", "LINK_KVKK": "kvkk"}
GENERATED_NOTE = "<!-- Generated by scripts/build-legal.py from legal/{lang}/{name}.md. Do not edit. -->\n\n"


def docs_link(document: str, lang: str) -> str:
    names = DOCUMENTS[document]
    target_lang = lang if lang in names else next(iter(names))
    name = names[target_lang]
    return f"{name}.md" if target_lang == lang else f"../{target_lang}/{name}.md"


def web_link(document: str, lang: str) -> str:
    return docs_link(document, lang).replace(".md", ".html")


def inline_html(text: str) -> str:
    text = html.escape(text, quote=False)
    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", lambda m: f'<a href="{html.escape(m.group(2))}">{m.group(1)}</a>', text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    return re.sub(r"(?<![*\w])\*(?!\s)(.+?)(?<!\s)\*(?![*\w])", r"<em>\1</em>", text)


def markdown_html(markdown: str) -> str:
    """The same small Markdown subset the app renders (AppCore MarkdownBlock)."""
    out: list[str] = []
    paragraph: list[str] = []
    quote: list[str] = []
    list_tag = ""

    def close_list() -> None:
        nonlocal list_tag
        if list_tag:
            out.append(f"</{list_tag}>")
            list_tag = ""

    def flush_paragraph() -> None:
        if paragraph:
            out.append(f"<p>{inline_html(' '.join(paragraph))}</p>")
            paragraph.clear()

    def flush_quote() -> None:
        if quote:
            out.append(f"<blockquote>{markdown_html(chr(10).join(quote))}</blockquote>")
            quote.clear()

    for raw in markdown.splitlines():
        line = raw.strip()
        if line.startswith(">"):
            flush_paragraph()
            close_list()
            quote.append(line[1:].strip())
            continue
        flush_quote()
        heading = re.match(r"^(#{1,6}) (.*)$", line)
        bullet = re.match(r"^[-*] (.*)$", line)
        numbered = re.match(r"^(\d{1,3})[.)] (.*)$", line)
        if not line:
            flush_paragraph()
            close_list()
        elif heading:
            flush_paragraph()
            close_list()
            level = len(heading.group(1))
            out.append(f"<h{level}>{inline_html(heading.group(2))}</h{level}>")
        elif line in ("---", "***", "___"):
            flush_paragraph()
            close_list()
            out.append("<hr>")
        elif bullet or numbered:
            flush_paragraph()
            tag = "ul" if bullet else "ol"
            if list_tag != tag:
                close_list()
                out.append(f"<{tag}>")
                list_tag = tag
            out.append(f"<li>{inline_html((bullet or numbered).groups()[-1])}</li>")
        else:
            close_list()
            paragraph.append(line)
    flush_paragraph()
    close_list()
    flush_quote()
    return "\n".join(out)


WEB_PAGE = """<!doctype html>
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} · Aybuke</title>
<meta name="description" content="{title} for Aybuke, the AI photo editor made for girls who glow.">
<link rel="icon" href="../../assets/icon.png">
<link rel="stylesheet" href="../../assets/site.css">
</head>
<body class="legal">
<header class="legal-header"><a class="brand" href="../../index.html"><img src="../../assets/icon.png" alt="" width="32" height="32"> Aybuke</a></header>
<main class="legal-body">
{content}
</main>
<footer class="legal-footer"><a href="../../index.html">glowlit</a> · <a href="{terms}">{terms_label}</a> · <a href="{privacy}">{privacy_label}</a></footer>
</body>
</html>
"""


def render(text: str, values: dict[str, str], links: dict[str, str]) -> str:
    def replace(match: re.Match) -> str:
        token = match.group(1)
        if token in links:
            return links[token]
        if token in values:
            return values[token]
        raise SystemExit(f"Unknown token {{{{{token}}}}}")

    # A line that uses an empty value is left out (no "KEP: " with nothing
    # after it, and nothing invented to fill the gap).
    kept = [line for line in text.split("\n")
            if not any(values.get(token) == "" for token in re.findall(r"\{\{([A-Z_]+)\}\}", line))]
    return re.sub(r"\{\{([A-Z_]+)\}\}", replace, "\n".join(kept))


def outputs() -> dict[Path, str]:
    config = json.loads((SOURCE / "config.json").read_text(encoding="utf-8"))
    result: dict[Path, str] = {}
    for document, names in DOCUMENTS.items():
        for lang, name in names.items():
            source = (SOURCE / lang / f"{name}.md").read_text(encoding="utf-8")
            values = {**config["shared"], **config[lang]}
            app_links = {token: f"glowlit-legal://{target}" for token, target in LINK_TOKENS.items()}
            web_links = {token: docs_link(target, lang) for token, target in LINK_TOKENS.items()}
            result[APP_OUT / lang / f"{name}.md"] = render(source, values, app_links)
            note = GENERATED_NOTE.format(lang=lang, name=name)
            result[DOCS_OUT / lang / f"{name}.md"] = note + render(source, values, web_links)
            page_links = {token: web_link(target, lang) for token, target in LINK_TOKENS.items()}
            body = render(source, values, page_links)
            title = body.splitlines()[0].lstrip("# ").strip()
            result[WEB_OUT / lang / f"{name}.html"] = WEB_PAGE.format(
                lang=lang,
                title=html.escape(title),
                content=markdown_html(body),
                terms=web_link("terms", lang),
                privacy=web_link("privacy", lang),
                terms_label="Kullanım Koşulları" if lang == "tr" else "Terms of Use",
                privacy_label="Gizlilik Politikası" if lang == "tr" else "Privacy Policy",
            )
    return result


def main() -> None:
    check = "--check" in sys.argv
    stale = []
    for path, content in outputs().items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    if check:
        if stale:
            print("Legal documents are out of date; run python3 scripts/build-legal.py:")
            for path in stale:
                print(f"  {path}")
            raise SystemExit(1)
        print("Legal documents are up to date.")
    else:
        print(f"Rendered {len(DOCUMENTS)} documents to {APP_OUT.relative_to(ROOT)}, {DOCS_OUT.relative_to(ROOT)} and {WEB_OUT.relative_to(ROOT)}.")


if __name__ == "__main__":
    main()
